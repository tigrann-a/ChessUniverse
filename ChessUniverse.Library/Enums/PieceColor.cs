namespace ChessUniverse.Library.Enums;

public enum PieceColor
{
    // enum-ը հաստատուն արժեքներով սահմանված արժեքների հավաքածու է
    // PieceColor-ը կարող է ունենալ միայն երկու արժեք White և Black
    // գաղափարապես ճիշտ է, քանի, որ գույնը սահմանափակ ընտրություն է, ոչ թե ազատ տեքստ
    // երբ ունենք փոքր քանակով հաստատուն արժեքներ, ապա enum-ը հարմար է օգտագործել
    White,  // 0
    Black   // 1
}
